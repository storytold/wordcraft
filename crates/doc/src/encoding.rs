        assert_eq!(oem_byte(857, 0xD5), '\u{FFFD}', "unassigned in 857");
        assert_eq!(decode(9999, &[0xE9]), "Θ", "unknown pages read as 437");
        for cp in OEM_CODE_PAGES {
            for b in 0..=255u8 {
                let _ = oem_byte(cp, b);
            }
        }
