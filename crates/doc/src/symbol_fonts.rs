//! Word's symbol fonts — Symbol, Wingdings, Wingdings 2, Wingdings 3 and Webdings — mapped to
//! standard Unicode characters, so text set in them shows the intended symbols when the font
//! isn't installed (they are proprietary and never bundled) and exports as real characters.
//!
//! Word stores a symbol-font character either as the private-use code U+F000 + the font's own
//! 8-bit code (U+F020–U+F0FF, what Insert › Symbol and `w:sym` write) or as the plain 8-bit code
//! (U+0020–U+00FF) in a run whose font is the symbol font. Both map the same way. The stored text
//! never changes: the mapping is for display, layout and plain-text output only.
//!
//! Sources (Unicode's own published data; no font file was read):
//! - Symbol: the Adobe Symbol encoding table published by Unicode,
//!   <https://www.unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt> (codes it maps to the
//!   private use area are left out; 0x6D maps to GREEK SMALL LETTER MU).
//! - Wingdings, Wingdings 2, Wingdings 3, Webdings: the correspondence tables in "Status of
//!   encoding of Wingdings and Webdings Symbols", Unicode L2/12-368 (WG2 N4384, M. Suignard,
//!   2012), the frozen repertoire of the Unicode 7.0 encoding (earlier drafts L2/11-052,
//!   L2/11-344), checked against the Unicode Character Database names. The one character not
//!   encoded (Wingdings 0xFF) has no entry.
//!
//! Tables are indexed by code − 0x20; 0 = no Unicode equivalent.

/// The symbol fonts this module knows, by lowercase family name.
fn table(family: &str) -> Option<&'static [u32; 224]> {
    let f = family.trim();
    if f.eq_ignore_ascii_case("symbol") || f.eq_ignore_ascii_case("symbol (pcl6)") {
        Some(&SYMBOL)
    } else if f.eq_ignore_ascii_case("wingdings") {
        Some(&WINGDINGS)
    } else if f.eq_ignore_ascii_case("wingdings 2") {
        Some(&WINGDINGS_2)
    } else if f.eq_ignore_ascii_case("wingdings 3") {
        Some(&WINGDINGS_3)
    } else if f.eq_ignore_ascii_case("webdings") {
        Some(&WEBDINGS)
    } else {
        None
    }
}

/// Whether `family` is one of Word's symbol fonts (Symbol, Wingdings, Wingdings 2, Wingdings 3,
/// Webdings), whose characters [`symbol_char`] maps.
pub fn is_symbol_font(family: &str) -> bool {
    table(family).is_some()
}

/// The standard Unicode character for `c` in a run set in the symbol font `family`: `c` is the
/// font's code stored as U+F020–U+F0FF or as U+0020–U+00FF (except the soft hyphen U+00AD).
/// `None` for other fonts, other characters and codes with no Unicode equivalent.
pub fn symbol_char(family: &str, c: char) -> Option<char> {
    let t = table(family)?;
    let u = u32::from(c);
    let code = match u {
        0xF020..=0xF0FF => u - 0xF000,
        // A soft hyphen stays a soft hyphen (Word stores `w:softHyphen` as U+00AD).
        0xAD => return None,
        0x20..=0xFF => u,
        _ => return None,
    };
    let i = usize::try_from(code.checked_sub(0x20)?).ok()?;
    t.get(i).copied().filter(|v| *v != 0).and_then(char::from_u32)
}

/// `text` (in a run set in `family`) with every symbol-font character replaced by its Unicode
/// equivalent; unchanged for other fonts.
pub fn map_text(family: &str, text: &str) -> String {
    if !is_symbol_font(family) {
        return text.to_string();
    }
    text.chars().map(|c| symbol_char(family, c).unwrap_or(c)).collect()
}

