#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_storage_forms_map_alike() {
        for f in ["Symbol", "Wingdings", "Wingdings 2", "Wingdings 3", "Webdings"] {
            assert!(is_symbol_font(f));
            for code in 0x20u32..=0xFF {
                let (Some(pua), Some(plain)) = (char::from_u32(0xF000 + code), char::from_u32(code)) else { continue };
                if code == 0xAD {
                    assert_eq!(symbol_char(f, plain), None);
                    continue;
                }
                assert_eq!(symbol_char(f, pua), symbol_char(f, plain), "{f} {code:#X}");
            }
        }
    }

    #[test]
    fn pcl6_symbol_encoding() {
        for family in ["Symbol (PCL6)", " symbol (pcl6) "] {
            assert!(is_symbol_font(family));
            for code in 0x20..=0xFF {
                let c = char::from_u32(code).unwrap();
                assert_eq!(symbol_char(family, c), symbol_char("Symbol", c));
                let pua = char::from_u32(0xF000 + code).unwrap();
                assert_eq!(symbol_char(family, pua), symbol_char("Symbol", pua));
            }
            assert_eq!(symbol_char(family, '\u{F0B3}'), Some('≥'));
        }
        assert!(!is_symbol_font("Symbol (unknown)"));
    }

    #[test]
    fn symbol_uses_the_adobe_symbol_encoding() {
        assert_eq!(symbol_char("Symbol", '\u{F061}'), Some('α'));
        assert_eq!(symbol_char("symbol", 'a'), Some('α'));
        assert_eq!(symbol_char("Symbol", 'm'), Some('μ'));
        assert_eq!(symbol_char("Symbol", 'W'), Some('Ω'));
        assert_eq!(symbol_char("Symbol", '\u{F0B7}'), Some('•'));
        assert_eq!(symbol_char("Symbol", '\u{F0A5}'), Some('∞'));
        assert_eq!(symbol_char("Symbol", '\u{F0D6}'), Some('√'));
        // The radical extender is private use in the Adobe table: no equivalent.
        assert_eq!(symbol_char("Symbol", '\u{F060}'), None);
    }

    #[test]
    fn wingdings_codes() {
        assert_eq!(symbol_char("Wingdings", '\u{F04A}'), Some('☺'));
        assert_eq!(symbol_char("Wingdings", 'J'), Some('☺'));
        assert_eq!(symbol_char("Wingdings", 'L'), Some('☹'));
        assert_eq!(symbol_char("Wingdings", '\u{F0FC}'), Some('✓'));
        assert_eq!(symbol_char("Wingdings", '\u{F0FE}'), Some('\u{1F5F9}'));
        assert_eq!(symbol_char("Wingdings", '\u{F06E}'), Some('◼'));
        assert_eq!(symbol_char("Wingdings", '\u{F0A7}'), Some('▪'));
        assert_eq!(symbol_char("Wingdings", '\u{F076}'), Some('❖'));
        assert_eq!(symbol_char("Wingdings", '\u{F028}'), Some('\u{1F57F}'));
        // The one character Unicode didn't encode.
        assert_eq!(symbol_char("Wingdings", '\u{F0FF}'), None);
    }

    #[test]
    fn wingdings_2_3_and_webdings_codes() {
        assert_eq!(symbol_char("Wingdings 2", '\u{F050}'), Some('\u{1F5F8}'));
        assert_eq!(symbol_char("Wingdings 2", 'O'), Some('\u{1F5F4}'));
        assert_eq!(symbol_char("Wingdings 2", '\u{F0FA}'), None);
        assert_eq!(symbol_char("Wingdings 3", '\u{F021}'), Some('⭠'));
        assert_eq!(symbol_char("Wingdings 3", '\u{F0F1}'), None);
        assert_eq!(symbol_char("Webdings", '\u{F059}'), Some('\u{1F394}'));
        assert_eq!(symbol_char("Webdings", 'a'), Some('\u{2714}'));
        assert_eq!(symbol_char("Webdings", '\u{F0FF}'), Some('\u{1F54A}'));
    }

    #[test]
    fn other_fonts_and_characters_are_left_alone() {
        assert!(!is_symbol_font("Arial"));
        assert_eq!(symbol_char("Arial", '\u{F04A}'), None);
        assert_eq!(symbol_char("Wingdings", '\u{1F600}'), None);
        assert_eq!(symbol_char("Wingdings", '\u{10FFFF}'), None);
        assert_eq!(symbol_char("Wingdings", '\u{1F}'), None);
        assert_eq!(map_text("Wingdings", "J\u{F04C}é"), "☺☹\u{1F879}");
        assert_eq!(map_text("Arial", "J\u{F04C}"), "J\u{F04C}");
    }
}
