/// Words of `list` by their first character, without the `|` marks, with the byte offsets of the
/// marks in the word (none for a compound).
fn by_first_char(list: &'static [&'static str]) -> HashMap<char, Vec<(String, Vec<usize>)>> {
    let mut m: HashMap<char, Vec<(String, Vec<usize>)>> = HashMap::new();
    for entry in list {
        let mut word = String::new();
        let mut marks = Vec::new();
        for c in entry.chars() {
            if c == '|' {
                marks.push(word.len());
            } else {
                word.push(c);
            }
        }
        if let Some(c) = word.chars().next() {
            m.entry(c).or_default().push((word, marks));
        }
    }
    m
}

fn compounds() -> &'static HashMap<char, Vec<(String, Vec<usize>)>> {
    static M: OnceLock<HashMap<char, Vec<(String, Vec<usize>)>>> = OnceLock::new();
    M.get_or_init(|| by_first_char(COMPOUNDS))
}

fn splits() -> &'static HashMap<char, Vec<(String, Vec<usize>)>> {
    static M: OnceLock<HashMap<char, Vec<(String, Vec<usize>)>>> = OnceLock::new();
    M.get_or_init(|| by_first_char(SPLITS))
}

/// The words of `table` that start at each word start in `run` of `text` and end at a word end:
/// (start, end, marks as offsets into `text`). `breaks` are the run's line break opportunities,
/// sorted.
fn whole_words(
    text: &str,
    run: &Range<usize>,
    breaks: &[usize],
    table: &HashMap<char, Vec<(String, Vec<usize>)>>,
) -> Vec<(usize, usize, Vec<usize>)> {
    // A word may end before paiyannoi or mai yamok, which then stays with it ("พนักงานฯ").
    let boundary = |i: usize| {
        i <= run.start || i >= run.end || breaks.binary_search(&i).is_ok() || text.get(i..).is_some_and(|s| s.starts_with(['\u{0E2F}', '\u{0E46}']))
    };
    let mut out = Vec::new();
    let Some(run_text) = text.get(run.clone()) else { return out };
    for (off, c) in run_text.char_indices() {
        let start = run.start + off;
        let Some(words) = table.get(&c) else { continue };
        if !boundary(start) {
            continue;
        }
        for (word, marks) in words {
            let end = start + word.len();
            if end <= run.end && text.get(start..end) == Some(word.as_str()) && boundary(end) {
                out.push((start, end, marks.iter().map(|m| start + m).collect()));
            }
        }
    }
    out
}

/// `breaks`, the sorted line break opportunities the ICU4X dictionary gives inside the Thai run
/// `run` of `text`, as Word breaks: none inside a compound Word keeps whole, and Word's breaks in a
/// word it splits (where `safe` allows a break).
pub(crate) fn adjust(text: &str, run: &Range<usize>, breaks: &mut Vec<usize>, safe: impl Fn(usize) -> bool) {
    let joined = whole_words(text, run, breaks, compounds());
    if !joined.is_empty() {
        breaks.retain(|&i| !joined.iter().any(|&(s, e, _)| s < i && i < e));
    }
    let split = whole_words(text, run, breaks, splits());
    let mut added = false;
    for (s, e, marks) in split {
        // A word with a break of its own inside is not this word; one inside a compound stays.
        if breaks.iter().any(|&i| s < i && i < e) || joined.iter().any(|&(js, je, _)| js <= s && e <= je && (js, je) != (s, e)) {
            continue;
        }
        for m in marks.into_iter().filter(|&m| safe(m)) {
            breaks.push(m);
            added = true;
        }
    }
    if added {
        breaks.sort_unstable();
        breaks.dedup();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every entry is Thai, once, and a split has at least one mark between two non-empty parts.
    #[test]
    fn the_lists_are_well_formed() {
        let thai = |w: &str| w.chars().all(|c| matches!(u32::from(c), 0x0E01..=0x0E5B));
        let mut seen = std::collections::HashSet::new();
        for w in COMPOUNDS {
            assert!(thai(w), "{w}");
            assert!(seen.insert(w.to_string()), "{w} twice");
        }
        for w in SPLITS {
            let parts: Vec<&str> = w.split('|').collect();
            assert!(parts.len() >= 2 && parts.iter().all(|p| !p.is_empty() && thai(p)), "{w}");
            assert!(seen.insert(w.replace('|', "")), "{w} twice or also a compound");
        }
    }

    fn adjusted(text: &str, breaks: &[usize]) -> Vec<usize> {
        let mut b = breaks.to_vec();
        adjust(text, &(0..text.len()), &mut b, |_| true);
        b
    }

    /// A compound between two breaks loses the break inside it; one that only overlaps a word, or
    /// whose end is not a break, keeps it.
    #[test]
    fn a_compound_that_is_a_word_of_its_own_stays_whole() {
        let text = "ฐานข้อมูลใหม่";
        let (inside, end) = ("ฐาน".len(), "ฐานข้อมูล".len());
        assert_eq!(adjusted(text, &[inside, end]), [end]);
        // Its end inside another word: left alone.
        assert_eq!(adjusted(text, &[inside]), [inside]);
    }

    /// A split word between two breaks gets Word's breaks; one inside a longer word doesn't.
    #[test]
    fn a_split_word_that_is_a_word_of_its_own_breaks_as_in_word() {
        let text = "หมายเหตุเข้าไป";
        let mark = "หมายเหตุ".len();
        assert_eq!(adjusted(text, &[mark]), ["หมาย".len(), mark, mark + "เข้า".len()]);
        // A break inside it already: not this word.
        assert_eq!(adjusted("หมายเหตุ", &["หม".len()]), ["หม".len()]);
    }
}
